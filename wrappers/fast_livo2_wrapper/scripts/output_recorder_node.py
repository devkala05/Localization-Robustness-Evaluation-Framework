#!/usr/bin/env python3
"""
output_recorder_node.py
=======================
Records all FAST-LIVO2 output topics to disk as they arrive.

Collected outputs
─────────────────
  /path               nav_msgs/Path        → trajectory_path.csv   (TUM format)
  /aft_mapped_to_init nav_msgs/Odometry    → odometry.csv
  /cloud_registered   sensor_msgs/PointCloud2  → recorded in output rosbag
  /cloud_registered_body sensor_msgs/PointCloud2  → recorded in output rosbag

The node also initiates a rosbag record subprocess so every FAST-LIVO2
output topic is captured in a bag for later replay and post-processing.

CSV / TUM format
────────────────
TUM trajectory format (used by evo, rpg_trajectory_evaluation):
    timestamp tx ty tz qx qy qz qw
    (space-separated, one pose per line, header line starts with #)

Output directory (default /data/output/) is created automatically.
"""

import os
import csv
import time
import subprocess
import threading
import signal
import sys

import rospy
from nav_msgs.msg   import Odometry, Path
from sensor_msgs.msg import PointCloud2
from geometry_msgs.msg import PoseStamped


# ─── Configuration defaults ───────────────────────────────────────────────────

DEFAULT_OUTPUT_DIR     = "/data/output"
DEFAULT_BAG_NAME       = "fast_livo2_output.bag"

# Topics to record into the output bag
RECORD_TOPICS = [
    "/path",
    "/aft_mapped_to_init",
    "/LIVO2/imu_propagate",
    "/cloud_registered",
    "/cloud_registered_body",
    "/camera/right/image_raw",
    "/livox/lidar",
    "/livox/imu",
    "/tf",
    "/tf_static",
]


# ─── CSV / TUM writers ────────────────────────────────────────────────────────

class TumTrajectoryWriter:
    """
    Writes poses from a nav_msgs/Path or individual PoseStamped messages
    to a file in TUM trajectory format:
        # timestamp tx ty tz qx qy qz qw
        1234567890.123  1.0  2.0  3.0  0.0  0.0  0.0  1.0
    """

    def __init__(self, filepath: str):
        self._filepath = filepath
        self._lock     = threading.Lock()
        os.makedirs(os.path.dirname(filepath), exist_ok=True)
        self._file = open(filepath, "w", newline="")
        self._file.write("# TUM trajectory format: timestamp tx ty tz qx qy qz qw\n")
        self._file.write("# Generated by fast_livo2_wrapper output_recorder_node\n")
        self._file.flush()
        self._count = 0
        rospy.loginfo("[OutputRecorder] TUM trajectory → %s", filepath)

    def write_pose(self, stamp: rospy.Time, pos, orient):
        """Write one pose line. pos and orient are geometry_msgs Point/Quaternion."""
        t = stamp.to_sec()
        line = (
            f"{t:.9f} "
            f"{pos.x:.9f} {pos.y:.9f} {pos.z:.9f} "
            f"{orient.x:.9f} {orient.y:.9f} {orient.z:.9f} {orient.w:.9f}\n"
        )
        with self._lock:
            self._file.write(line)
            self._count += 1
            if self._count % 100 == 0:
                self._file.flush()

    def close(self):
        with self._lock:
            self._file.flush()
            self._file.close()
        rospy.loginfo("[OutputRecorder] Trajectory saved: %d poses → %s",
                      self._count, self._filepath)


class OdometryCsvWriter:
    """
    Writes nav_msgs/Odometry messages to CSV with full pose + twist.

    Columns:
        timestamp, pos_x, pos_y, pos_z,
        qx, qy, qz, qw,
        vel_x, vel_y, vel_z,
        ang_x, ang_y, ang_z
    """

    HEADER = [
        "timestamp",
        "pos_x", "pos_y", "pos_z",
        "qx", "qy", "qz", "qw",
        "vel_x", "vel_y", "vel_z",
        "ang_vel_x", "ang_vel_y", "ang_vel_z",
    ]

    def __init__(self, filepath: str):
        self._filepath = filepath
        self._lock     = threading.Lock()
        os.makedirs(os.path.dirname(filepath), exist_ok=True)
        self._file   = open(filepath, "w", newline="")
        self._writer = csv.writer(self._file)
        self._writer.writerow(self.HEADER)
        self._count  = 0
        rospy.loginfo("[OutputRecorder] Odometry CSV → %s", filepath)

    def write(self, msg: Odometry):
        p = msg.pose.pose.position
        q = msg.pose.pose.orientation
        v = msg.twist.twist.linear
        w = msg.twist.twist.angular
        row = [
            f"{msg.header.stamp.to_sec():.9f}",
            f"{p.x:.9f}", f"{p.y:.9f}", f"{p.z:.9f}",
            f"{q.x:.9f}", f"{q.y:.9f}", f"{q.z:.9f}", f"{q.w:.9f}",
            f"{v.x:.9f}", f"{v.y:.9f}", f"{v.z:.9f}",
            f"{w.x:.9f}", f"{w.y:.9f}", f"{w.z:.9f}",
        ]
        with self._lock:
            self._writer.writerow(row)
            self._count += 1
            if self._count % 100 == 0:
                self._file.flush()

    def close(self):
        with self._lock:
            self._file.flush()
            self._file.close()
        rospy.loginfo("[OutputRecorder] Odometry saved: %d rows → %s",
                      self._count, self._filepath)


# ─── Rosbag recorder ─────────────────────────────────────────────────────────

class BagRecorder:
    """
    Spawns a ``rosbag record`` subprocess capturing all FAST-LIVO2 output
    topics. The bag is finalised cleanly on node shutdown.
    """

    def __init__(self, output_dir: str, bag_name: str, topics: list):
        self._bag_path = os.path.join(output_dir, bag_name)
        os.makedirs(output_dir, exist_ok=True)

        cmd = ["rosbag", "record", "-O", self._bag_path] + topics
        rospy.loginfo("[BagRecorder] Starting: %s", " ".join(cmd))

        self._proc = subprocess.Popen(
            cmd,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
        )
        rospy.loginfo("[BagRecorder] Bag recording started → %s", self._bag_path)

    def stop(self):
        """Send SIGINT to rosbag so it finalises the index cleanly."""
        if self._proc and self._proc.poll() is None:
            rospy.loginfo("[BagRecorder] Stopping bag recording …")
            self._proc.send_signal(signal.SIGINT)
            try:
                self._proc.wait(timeout=10)
            except subprocess.TimeoutExpired:
                self._proc.kill()
            rospy.loginfo("[BagRecorder] Bag saved → %s", self._bag_path)


# ─── Main recorder node ───────────────────────────────────────────────────────

class OutputRecorderNode:

    def __init__(self):
        output_dir = rospy.get_param("~output_dir",  DEFAULT_OUTPUT_DIR)
        bag_name   = rospy.get_param("~bag_name",    DEFAULT_BAG_NAME)
        record_bag = rospy.get_param("~record_bag",  True)

        os.makedirs(output_dir, exist_ok=True)

        # ── CSV writers ────────────────────────────────────────────────────────
        self._tum_writer  = TumTrajectoryWriter(
            os.path.join(output_dir, "trajectory_tum.txt")
        )
        self._odom_writer = OdometryCsvWriter(
            os.path.join(output_dir, "odometry.csv")
        )
        self._pose_count  = 0
        self._cloud_count = 0

        # ── Optional rosbag recorder ───────────────────────────────────────────
        self._bag_recorder = None
        if record_bag:
            self._bag_recorder = BagRecorder(output_dir, bag_name, RECORD_TOPICS)

        # ── Subscribers (FAST-LIVO2 output topics) ─────────────────────────────
        rospy.Subscriber("/path",                Path,        self._path_cb,  queue_size=5)
        rospy.Subscriber("/aft_mapped_to_init",  Odometry,    self._odom_cb,  queue_size=100)
        rospy.Subscriber("/cloud_registered",    PointCloud2, self._cloud_cb, queue_size=5)

        # Register shutdown hook for clean file finalisation
        rospy.on_shutdown(self._on_shutdown)

        rospy.loginfo(
            "[OutputRecorder] Collecting FAST-LIVO2 outputs → %s", output_dir
        )

    # ── Callbacks ──────────────────────────────────────────────────────────────

    def _path_cb(self, msg: Path):
        """Write all poses in the path message to the TUM file.

        FAST-LIVO2 publishes the full accumulated path on each update, so
        we only write new poses (those past the current file length).
        """
        n = len(msg.poses)
        if n <= self._pose_count:
            return
        for pose_stamped in msg.poses[self._pose_count:]:
            self._tum_writer.write_pose(
                pose_stamped.header.stamp,
                pose_stamped.pose.position,
                pose_stamped.pose.orientation,
            )
        self._pose_count = n

    def _odom_cb(self, msg: Odometry):
        self._odom_writer.write(msg)
        # Also write each odometry pose to TUM for high-rate trajectory
        self._tum_writer.write_pose(
            msg.header.stamp,
            msg.pose.pose.position,
            msg.pose.pose.orientation,
        )

    def _cloud_cb(self, msg: PointCloud2):
        self._cloud_count += 1
        if self._cloud_count % 100 == 0:
            rospy.loginfo("[OutputRecorder] Received %d point clouds",
                          self._cloud_count)

    # ── Shutdown ────────────────────────────────────────────────────────────────

    def _on_shutdown(self):
        rospy.loginfo("[OutputRecorder] Shutdown — finalising output files …")
        self._tum_writer.close()
        self._odom_writer.close()
        if self._bag_recorder:
            self._bag_recorder.stop()


def main():
    rospy.init_node("output_recorder_node", anonymous=False)
    _node = OutputRecorderNode()
    rospy.spin()


if __name__ == "__main__":
    main()
